def _row(name: str, label: str, description: str, detection: str,
         run: Callable[[Any, AttackContext, AccessPoint], AttackOutcome], *,
         cls_name: str = "", impact: str = "info", noise: str = "silent",
         category: str = "offline") -> type:
    """Build one audit class from a function, and put it in this module's namespace.

    A wave of fourteen audits is fourteen subclasses of the same shape: a name, a label,
    the metadata the catalogue prints, and one function that does the reading.  Building
    them from a row keeps the class boilerplate out of the way of the analysis, which is
    the part that has to be right.
    """
    cls = type(cls_name or "".join(part.capitalize() for part in name.split("_")) + "Attack",
               (_BtAudit,), {
                   "name": name, "label": label, "tool": "wifipilot bt.py (own BLE decoder)",
                   "description": description, "detection": detection, "impact": impact,
                   "noise": noise, "category": category, "scene": True, "run": run,
               })
    cls.__doc__ = description
    cls.__module__ = __name__
    globals()[cls.__name__] = cls
    return cls


def _add(name: str, label: str, description: str, detection: str,
         run: Callable[..., AttackOutcome], **kwargs: Any) -> type:
    """Register an audit row, metadata and all."""
    cls = _row(name, label, description, detection, run, **kwargs)
    REGISTRY.append((name, {"category": kwargs.get("category", "offline"),
                            "noise": kwargs.get("noise", "silent"),
                            "impact": kwargs.get("impact", "info"),
                            "detection": detection}, cls))
    return cls


