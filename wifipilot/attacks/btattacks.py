"""Bluetooth and Bluetooth Low Energy attacks: the radio next door to Wi-Fi.

Wi-Fi is one of two radios in every phone, every laptop and every door sensor, and the
one next to it is Bluetooth.  This module is the toolkit's second radio: it reads a
Bluetooth Low Energy capture the way the offline wave reads a Wi-Fi one — beacons that
are identifiable, a tracker that follows a person from one floor to the next, a link
that paired with Just Works and no Secure Connections — and it performs the on-air work
that a Wi-Fi-only assessment never sees.

Three kinds of attack live here:

* **Audits.**  Offline work over a ``LINKTYPE_BLUETOOTH_LE_LL_WITH_PHDR`` capture: the
  device census, the tracker detection and tracking, the beacon and Eddystone decoders,
  the address-privacy check, the manufacturer and service census, the interval and
  channel analyses, and the audits of what the devices are *offering* — connectable
  advertising, pairing configurations, GATT structure, link-layer features.
* **On air, advertising.**  The Bluetooth equivalent of the rogue-infrastructure wave:
  a name flood, a beacon clone, a tracker clone, a connectable lure.
* **On air, links.**  The attacks that talk to a device: LE scanning and classic
  inquiry, the pairing-abuse floods, the L2CAP echo flood, SDP browsing, RFCOMM
  discovery and GATT enumeration.

Everything that transmits is opt-in, is bounded by ``config.bt_timeout``, and reports
what it actually did; everything that only reads works in demo mode against a real
capture generated by ``synth.build_bt_scene``.
"""

