class _BtAudit(_Audit):
    """An offline Bluetooth audit: read a capture of the radio, not of the air."""

    category = "offline"
    noise = "silent"
    impact = "info"
    scene = True
    tool = "wifipilot bt.py (own Bluetooth LE decoder)"

    def demo_scene(self, ctx: AttackContext, ap: AccessPoint) -> str:
        """A BLE capture of the simulated floor: beacons, trackers, sensors, one connection.

        Demo mode reads the *same* floor the on-air attacks meet — :mod:`wifipilot.blesim`
        writes the capture, so the census an analyst reads offline and the devices an
        operator talks to on air are one estate rather than two, and a report that names
        a tracker names the device rather than a description of one.
        """
        from .. import blesim

        path = os.path.join(ctx.session.state_dir, "captures",
                            f"bluetooth-{ap.bssid.replace(':', '')}.pcap")
        if not os.path.exists(path):
            os.makedirs(os.path.dirname(path), exist_ok=True)
            blesim.write_capture(path, seconds=20.0,
                                 seed=int(ap.bssid.replace(":", ""), 16) % 997)
        return path

    def scan(self, ctx: AttackContext, ap: AccessPoint
             ) -> Tuple[Dict[str, bt.BluetoothDevice], List[Tuple[float, Dict[str, Any]]],
                        str]:
        """Read the capture into a device map plus the raw records."""
        path = self.capture(ctx, ap)
        if not path or not os.path.exists(path):
            return {}, [], ""
        devices: Dict[str, bt.BluetoothDevice] = {}
        packets: List[Tuple[float, Dict[str, Any]]] = []
        for stamp, packet in bt.iter_le_frames(path):
            packets.append((stamp, packet))
            if packet.get("advertising"):
                bt.merge_observations(devices, packet, stamp)
        return devices, packets, path

    @staticmethod
    def intervals(device: bt.BluetoothDevice) -> List[float]:
        """The gaps between one device's advertisements, in milliseconds."""
        stamps = sorted(packet.get("timestamp") or 0.0 for packet in device.raw)
        gaps = [round((later - earlier) * 1000.0, 1)
                for earlier, later in zip(stamps, stamps[1:])]
        return gaps

    @staticmethod
    def median(values: Sequence[float]) -> float:
        ordered = sorted(values)
        if not ordered:
            return 0.0
        middle = len(ordered) // 2
        if len(ordered) % 2:
            return ordered[middle]
        return (ordered[middle - 1] + ordered[middle]) / 2.0


def _census_devices(ctx: AttackContext, ap: AccessPoint, attack: _BtAudit
                    ) -> Tuple[Dict[str, bt.BluetoothDevice], List[Tuple[float,
                                                                        Dict[str, Any]]],
                               str]:
    return attack.scan(ctx, ap)


def _hot_count(devices: Dict[str, bt.BluetoothDevice], floor: int = 300) -> Dict[str, int]:
    """Devices by manufacturer, most common first."""
    counts: Dict[str, int] = {}
    for device in devices.values():
        key = device.company or "unknown"
        counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items(), key=lambda item: -item[1])[:floor])


