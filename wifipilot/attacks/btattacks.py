def _device_census(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Every Bluetooth device in the capture, with what its advertisement said.

    A Bluetooth device that is awake is *always* talking: advertising is how LE devices
    are discovered, and a scan of a building for a few minutes finds badges, watches,
    sensors, beacons, televisions and the phones that belong to the people carrying them.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    connectable = [device for device in devices.values() if device.connectable]
    named = [device for device in devices.values() if device.name]
    beacons = [device for device in devices.values() if device.beacon]
    detail = (f"{len(devices)} device(s) on air: {len(named)} named, "
              f"{len(connectable)} connectable, {len(beacons)} with a beacon payload")
    rows = []
    for device in sorted(devices.values(), key=lambda item: -item.observations)[:60]:
        row = device.to_dict()
        row["median_interval_ms"] = self.median(self.intervals(device))
        row["channels"] = sorted(set(device.channels))
        rows.append(row)
    return self._report(ctx, ap, attempt, f"Bluetooth devices: {len(devices)}", detail,
                        {"devices": rows, "connectable": len(connectable),
                         "named": len(named), "capture": path}, severity="info")


def _tracker_detect(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Find the devices that follow people: AirTags, Tiles, SmartTags and Find My.

    Apple's network, Google's, Samsung's and Tile's all work the same way: a tag
    advertises a rotating address and an encrypted payload, and any phone that hears it
    uploads the sighting.  The plaintext the tag broadcasts still identifies the
    *manufacturer and the product class*, which is what a privacy check has to report.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    trackers = [device for device in devices.values() if device.tracker]
    rows = []
    for device in trackers:
        row = device.to_dict()
        row.update({"tracker": device.tracker, "median_interval_ms":
                    self.median(self.intervals(device))})
        rows.append(row)
    # tracker_of() names the vendor and the product, and both matter: "Apple Find My"
    # says a phone network can see it, "Tile" says a different one can
    products = sorted({f"{row['tracker'].get('vendor', '')} {row['tracker'].get('product', '')}".strip()
                       for row in rows if row.get("tracker")})
    detail = (f"{len(trackers)} tracker(s) of {len(devices)} device(s): "
              + (", ".join(products) if products else "none"))
    return self._report(ctx, ap, attempt, f"Trackers: {len(trackers)}", detail,
                        {"trackers": rows[:40], "capture": path},
                        severity="medium" if trackers else "info")


def _tracker_follow(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Follow one address through a capture: how long it was seen, and how often.

    A tracker that a phone can follow is a tracker that anybody with a receiver can
    follow.  This attack does not decrypt anything — it counts, and the count is the
    finding: a device advertising every two seconds for twenty minutes is a device whose
    movements are in somebody's database.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    if not devices:
        return self._fail(ctx, ap, attempt, "no devices in the capture",
                          severity="info")
    busiest = max(devices.values(), key=lambda device: device.seconds_seen)
    intervals = self.intervals(busiest)
    timeline = [{"stamp": round(device.first_seen, 3), "address": device.address}
                for device in devices.values()][:1]
    detail = (f"{busiest.display_name} ({busiest.address}) was on air for "
              f"{busiest.seconds_seen:.1f}s in {busiest.observations} advertisement(s), "
              f"a median interval of {self.median(intervals):.1f} ms")
    return self._report(ctx, ap, attempt,
                        f"Trackable device: {busiest.display_name} for "
                        f"{busiest.seconds_seen:.0f}s", detail,
                        {"device": busiest.to_dict(), "intervals": intervals[:60],
                         "capture": path, "first_seen": timeline},
                        severity="medium" if busiest.seconds_seen > 30 else "info")


def _ibeacon_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Inventory the iBeacons: proximity UUID, major, minor and measured power.

    An iBeacon is a plaintext identity: the proximity UUID usually names the deployment
    (a chain, a building, a product line), and the major/minor pair usually names the
    room.  That is what an attacker needs to clone one, and what a survey needs to map
    an estate.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    beacons = []
    for device in devices.values():
        if (device.beacon or {}).get("kind") != "iBeacon":
            continue
        entry = dict(device.beacon)
        entry.update({"address": device.address, "rssi": device.rssi,
                      "observations": device.observations})
        beacons.append(entry)
    groups: Dict[str, List[Dict[str, Any]]] = {}
    for entry in beacons:
        groups.setdefault(entry["uuid"], []).append(entry)
    detail = (f"{len(beacons)} iBeacon(s) in {len(groups)} deployment(s)"
              + (f": {', '.join(f'{uuid[:8]}…(major/minor {len(rows)} point(s))' for uuid, rows in list(groups.items())[:3])}"
                 if groups else ""))
    return self._report(ctx, ap, attempt, f"iBeacons: {len(beacons)}", detail,
                        {"beacons": beacons[:40],
                         "deployments": {uuid: len(rows) for uuid, rows in groups.items()},
                         "capture": path},
                        severity="info")


def _eddystone_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint
                     ) -> AttackOutcome:
    """Eddystone frames: URLs, UIDs, and the accuracy that pairs with each one.

    Google's beacon format carries a URL directly, in a form short enough for a 31-byte
    advertising packet.  A capture of one is a list of the places a physical web
    deployment sends people — and, when a URL is stale or a UID is never rotated, a
    record of what the estate forgot to maintain.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    frames = []
    for device in devices.values():
        beacon = device.beacon or {}
        if not str(beacon.get("kind", "")).startswith("Eddystone"):
            continue
        entry = dict(beacon)
        entry.update({"address": device.address, "rssi": device.rssi})
        frames.append(entry)
    urls = [entry for entry in frames if entry.get("url")]
    detail = (f"{len(frames)} Eddystone frame(s): {len(urls)} URL(s)"
              + (f" — {', '.join(entry['url'] for entry in urls[:4])}" if urls else ""))
    return self._report(ctx, ap, attempt, f"Eddystone frames: {len(frames)}", detail,
                        {"frames": frames[:40], "capture": path}, severity="info")


def _address_privacy(self: _BtAudit, ctx: AttackContext, ap: AccessPoint
                     ) -> AttackOutcome:
    """Which devices rotate their address, and which one is a fingerprint.

    LE lets a device advertise a *resolvable private address* that changes every few
    minutes, so a scanner cannot link two sightings.  A device with a public or static
    address — a beacon, a badge, most fitness equipment, far too many sensors — can be
    followed for months by anybody who writes down one number.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    fixed = [device for device in devices.values()
             if device.address_kind in ("public", "random static", "")]
    rotating = [device for device in devices.values()
                if device.address_kind in ("resolvable private", "non-resolvable private")]
    detail = (f"{len(devices)} device(s): {len(rotating)} rotate their address, "
              f"{len(fixed)} keep one for the whole capture"
              + (f" — {', '.join(device.address for device in fixed[:5])}" if fixed else ""))
    return self._report(ctx, ap, attempt,
                        f"Fixed addresses: {len(fixed)}/{len(devices)}", detail,
                        {"fixed": [device.to_dict() for device in fixed][:40],
                         "rotating": len(rotating), "capture": path},
                        severity="medium" if len(fixed) > len(rotating) else "info")


def _manufacturer_census(self: _BtAudit, ctx: AttackContext, ap: AccessPoint
                         ) -> AttackOutcome:
    """Who made everything on air, from the manufacturer field alone.

    Company identifiers are assigned by the Bluetooth SIG and are not encrypted, so a
    capture says which vendors are installed in a building — including the ones whose
    presence an asset register does not explain.  An unrecognised identifier is worth
    exactly as much as a recognised one.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    counts = _hot_count(devices)
    named = [device for device in devices.values() if device.name]
    detail = (f"{len(counts)} manufacturer(s) across {len(devices)} device(s): "
              + ", ".join(f"{name} ×{count}" for name, count in list(counts.items())[:6]))
    return self._report(ctx, ap, attempt, f"Manufacturers: {len(counts)}", detail,
                        {"manufacturers": counts, "named": len(named),
                         "devices": [device.to_dict() for device in devices.values()][:40],
                         "capture": path},
                        severity="info")


def _service_census(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """What the devices say they do: services, appearances and beacon payloads.

    A device advertises the services it supports, and those services are its function:
    a heart-rate service is a strap, a HID service is a keyboard, an alert service is a
    tag looking for its owner.  Grouping a floor by advertised service is the fastest
    inventory an assessment can produce.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    counts: Dict[str, int] = {}
    for device in devices.values():
        for name in device.services or ["(none advertised)"]:
            counts[name] = counts.get(name, 0) + 1
    appearances = {device.appearance for device in devices.values() if device.appearance}
    detail = (f"{len(counts)} advertised service(s) across {len(devices)} device(s): "
              + ", ".join(f"{name} ×{count}"
                          for name, count in sorted(counts.items(),
                                                    key=lambda item: -item[1])[:6]))
    return self._report(ctx, ap, attempt, f"Advertised services: {len(counts)}", detail,
                        {"services": counts, "appearances": sorted(appearances),
                         "capture": path}, severity="info")


def _interval_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Advertising intervals: the ones that are wrong, and what they cost.

    An LE advertisement has a recommended interval: fast for a device that wants a
    connection now, slow for a beacon that has to last a year on a coin cell.  A device
    at 20 ms is burning its battery for nothing; a device at one per second in a
    connection-oriented role is slow enough to be missed.  The interval also decides
    whether an assessment can see the device at all.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    rows = []
    for device in devices.values():
        gaps = self.intervals(device)
        if len(gaps) < 3:
            continue
        median = self.median(gaps)
        rows.append({"address": device.address, "name": device.display_name,
                     "median_ms": median, "min_ms": min(gaps), "max_ms": max(gaps),
                     "samples": len(gaps), "rssi": device.rssi,
                     "verdict": ("aggressive" if median <= 30 else
                                 "active" if median <= 200 else
                                 "beacon-like" if median <= 1200 else "slow")})
    aggressive = [row for row in rows if row["verdict"] == "aggressive"]
    slow = [row for row in rows if row["verdict"] == "slow"]
    detail = (f"{len(rows)} device(s) with enough advertisements to measure: "
              f"{len(aggressive)} at 30 ms or less, {len(slow)} slower than 1.2 s")
    return self._report(ctx, ap, attempt, f"Interval audit: {len(rows)} device(s)", detail,
                        {"devices": sorted(rows, key=lambda row: row["median_ms"])[:40],
                         "capture": path},
                        severity="info")


def _channel_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Which of the three advertising channels the devices use.

    LE advertising lives on 37, 38 and 39 — the three channels between the Wi-Fi ones,
    chosen to survive interference.  A device that transmits on only one channel is a
    device that half the scanners in a building never see; a device that moves between
    them is doing what the specification asks.  The channel counts also show whether the
    capture itself was taken with a scanner that hops.
    """
    attempt = self._attempt(ctx, ap)
    devices, packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    totals = {channel: 0 for channel in bt.ADV_CHANNELS}
    for _stamp, packet in packets:
        channel = packet.get("channel")
        if channel in totals:
            totals[channel] += 1
    single = []
    for device in devices.values():
        channels = sorted(set(device.channels))
        if len(channels) == 1:
            single.append({"address": device.address, "name": device.display_name,
                           "channel": channels[0]})
    detail = (f"channel usage {totals}; {len(single)} device(s) fixed to one channel")
    return self._report(ctx, ap, attempt,
                        f"Advertising channels: {len(totals)} in use", detail,
                        {"totals": totals, "single_channel": single[:20], "capture": path},
                        severity="info")


def _connectable_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint
                       ) -> AttackOutcome:
    """Devices that accept a connection, and what that exposes.

    Advertising that is *connectable* means the device will accept a link from anybody
    who asks.  For a beacon that is a configuration mistake; for a sensor it is the
    product; for a lock it is the attack surface.  This audit separates the two and
    names the ones that are listening.
    """
    attempt = self._attempt(ctx, ap)
    devices, _packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    open_devices = sorted((device for device in devices.values() if device.connectable),
                          key=lambda device: device.rssi, reverse=True)
    rows = [{"address": device.address, "name": device.display_name, "rssi": device.rssi,
             "services": device.services, "beacon": (device.beacon or {}).get("kind", "")}
            for device in open_devices]
    detail = (f"{len(rows)} of {len(devices)} device(s) accept a connection"
              + (f"; the loudest is {rows[0]['address']} ({rows[0]['name'] or 'unnamed'})"
                 f" at {rows[0]['rssi']} dBm" if rows else ""))
    return self._report(ctx, ap, attempt, f"Connectable: {len(rows)}", detail,
                        {"connectable": rows[:40], "capture": path},
                        severity="medium" if rows else "info")


def _pairing_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """What a captured pairing exchange says: Just Works, no MITM, no Secure Connections.

    A pairing request is plaintext on the link, and it names the IO capabilities, the
    authentication requirements and the key size the two ends agreed on.  "Just Works"
    means no protection against an active machine-in-the-middle; no Secure Connections
    means the legacy key exchange, whose entropy an attacker can exhaust in real time;
    a key size below 16 bytes is a downgrade somebody asked for.
    """
    attempt = self._attempt(ctx, ap)
    _devices, packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    pairings: List[Dict[str, Any]] = []
    for _stamp, packet in packets:
        if packet.get("advertising"):
            continue
        parsed = bt.parse_data_channel(packet.get("frame") or b"")
        smp = parsed.get("smp")
        if smp and smp.get("command") in (0x01, 0x02):
            pairings.append(smp)
    weak = [entry for entry in pairings
            if entry.get("just_works") or not entry.get("secure_connections")
            or (entry.get("max_key_size") or 16) < 16]
    detail = (f"{len(pairings)} pairing exchange(s) in the capture"
              + (f"; {len(weak)} used Just Works, legacy pairing or a shortened key"
                 if weak else "; all of them asked for Secure Connections with MITM"))
    return self._report(ctx, ap, attempt, f"Pairing exchanges: {len(pairings)}", detail,
                        {"pairings": pairings, "weak": len(weak), "capture": path},
                        severity="medium" if weak else "info")


def _gatt_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """The GATT structure of a captured connection: services, handles and what is open.

    A BLE connection exposes an attribute table, and the table is the device's API: a
    heart-rate service, a battery level, and — on the devices that get this wrong — a
    vendor service with writable characteristics that reconfigure it.  Reading the table
    out of a capture is how the finding is proved without touching the device again.
    """
    attempt = self._attempt(ctx, ap)
    _devices, packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    entries: List[Dict[str, Any]] = []
    writes: List[Dict[str, Any]] = []
    for _stamp, packet in packets:
        if packet.get("advertising"):
            continue
        parsed = bt.parse_data_channel(packet.get("frame") or b"")
        att = parsed.get("att") or {}
        for entry in att.get("entries") or []:
            entries.append(entry)
        if att.get("opcode") in (0x12, 0x52):                       # write / write command
            writes.append({"opcode": att.get("opcode"), "handle": att.get("handle"),
                           "value": (att.get("value") or b"").hex()})
    services = bt.gatt_services_from_att(entries)
    detail = (f"{len(services)} service(s) and {len(entries)} attribute(s) in the capture"
              + (f"; {len(writes)} write(s) to the table" if writes else ""))
    return self._report(ctx, ap, attempt, f"GATT: {len(services)} service(s)", detail,
                        {"services": services[:40], "entries": entries[:60],
                         "writes": writes[:20], "capture": path},
                        severity="info")


def _feature_audit(self: _BtAudit, ctx: AttackContext, ap: AccessPoint) -> AttackOutcome:
    """Link-layer features and control PDUs: what the link is willing to do.

    The feature exchange tells an auditor which link-layer procedures a device supports:
    LE Encryption, the Data Packet Length Extension, LE 2M PHY, channel selection, and
    the privacy features.  A device that does not support LE Encryption at all cannot
    encrypt the link, whatever the application layer claims.
    """
    attempt = self._attempt(ctx, ap)
    _devices, packets, path = self.scan(ctx, ap)
    if not path:
        return self._need_capture(ctx, ap, attempt, "Bluetooth capture")
    controls: Dict[str, int] = {}
    features: Dict[str, bool] = {}
    for _stamp, packet in packets:
        if packet.get("advertising"):
            continue
        parsed = bt.parse_data_channel(packet.get("frame") or b"")
        header = parsed.get("ll") or {}
        if header.get("control"):
            controls[header["control"]] = controls.get(header["control"], 0) + 1
        if header.get("features"):
            features.update(header["features"])
    missing = sorted(name for name, present in features.items() if not present)
    detail = (f"{len(controls)} control PDU kind(s)"
              + (f"; {len(features)} feature bit(s) read" if features else "")
              + (f"; not supported: {', '.join(missing[:6])}" if missing else ""))
    return self._report(ctx, ap, attempt,
                        f"Link-layer: {len(controls)} control PDU kind(s)", detail,
                        {"controls": controls, "features": features, "capture": path},
                        severity="info")


